#!/usr/bin/env python3
"""Generate the reviewed partial Luau Engine definitions from a pinned API dump."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs/research/engine-api-surface.json"
OUTPUT = ROOT / "crates/studio-luau/native/definitions/roblox-engine-0.745.0.7451137.luau"
MAX_DUMP_BYTES = 64 * 1024 * 1024
CHUNK_SIZE = 1024 * 1024


class GenerationError(Exception):
    pass


def cache_path(upload_id: str) -> Path:
    xdg_cache = os.environ.get("XDG_CACHE_HOME")
    cache_root = Path(xdg_cache).expanduser() if xdg_cache else Path.home() / ".cache"
    return (
        cache_root
        / "roblox-studio-linux"
        / "studio-reference"
        / "api-dumps"
        / f"{upload_id}-API-Dump.json"
    )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(CHUNK_SIZE):
            digest.update(chunk)
    return digest.hexdigest()


def load_json(path: Path, description: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise GenerationError(f"Could not read {description} JSON at {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise GenerationError(f"{description} must be a JSON object")
    return value


def api_type(value: dict[str, Any], mapping: dict[str, str], where: str) -> str:
    category = value.get("Category")
    name = value.get("Name")
    if not isinstance(category, str) or not isinstance(name, str):
        raise GenerationError(f"{where} has a malformed API type")
    key = f"{category}.{name}"
    try:
        return mapping[key]
    except KeyError as exc:
        raise GenerationError(
            f"{where} uses unsupported type {key!r}; add an explicit reviewed mapping"
        ) from exc


def generate(manifest: dict[str, Any], api_dump: dict[str, Any]) -> str:
    reference = manifest.get("reference")
    if not isinstance(reference, dict):
        raise GenerationError("manifest has no reference metadata")
    classes_config = manifest.get("classes")
    if not isinstance(classes_config, dict) or not classes_config:
        raise GenerationError("manifest has no class allowlist")
    if api_dump.get("Version") != reference.get("schemaVersion"):
        raise GenerationError("API dump schema version does not match the reviewed manifest")

    raw_classes = api_dump.get("Classes")
    raw_enums = api_dump.get("Enums")
    if not isinstance(raw_classes, list) or not isinstance(raw_enums, list):
        raise GenerationError("API dump is missing Classes or Enums arrays")
    if len(raw_classes) != reference.get("classCount") or len(raw_enums) != reference.get("enumCount"):
        raise GenerationError("API dump class/enum counts differ from the reviewed manifest")

    classes = {
        value.get("Name"): value
        for value in raw_classes
        if isinstance(value, dict) and isinstance(value.get("Name"), str)
    }
    if len(classes) != len(raw_classes):
        raise GenerationError("API dump contains malformed or duplicate class names")
    for class_name in classes_config:
        if class_name not in classes:
            raise GenerationError(f"allowlisted class {class_name!r} is absent from the API dump")

    overrides = manifest.get("manualTypeOverrides", {})
    mappings = manifest.get("typeMappings", {})
    if not isinstance(overrides, dict) or not isinstance(mappings, dict):
        raise GenerationError("type overrides and mappings must be JSON objects")

    lines = [
        "-- Generated by scripts/generate_studio_engine_types.py; do not edit by hand.",
        "-- Source: " + str(reference.get("apiDumpUrl")),
        "-- Studio version: " + str(reference.get("studioVersion")),
        "-- Upload ID: " + str(reference.get("uploadId")),
        "-- API dump SHA-256: " + str(reference.get("apiDumpSha256")),
        "-- This is a reviewed partial type surface, not a complete Engine model.",
        "",
    ]

    for class_name, allowlist in classes_config.items():
        if not isinstance(allowlist, dict):
            raise GenerationError(f"allowlist for {class_name} must be an object")
        class_info = classes[class_name]
        superclass = class_info.get("Superclass")
        if superclass in (None, "Object"):
            superclass = None
        elif superclass not in classes_config:
            raise GenerationError(
                f"allowlisted class {class_name!r} has unallowlisted ancestor {superclass!r}"
            )
        if superclass is not None:
            lines.append(f"declare extern type {class_name} extends {superclass} with")
        else:
            lines.append(f"declare extern type {class_name} with")

        member_list = class_info.get("Members", [])
        members = {
            (member.get("MemberType"), member.get("Name")): member
            for member in member_list
            if isinstance(member, dict)
        }
        requested_properties = allowlist.get("properties", [])
        requested_functions = allowlist.get("functions", [])
        if not isinstance(requested_properties, list) or not isinstance(requested_functions, list):
            raise GenerationError(f"property/function allowlists for {class_name} must be arrays")

        declarations: list[str] = []
        for property_name in requested_properties:
            member = members.get(("Property", property_name))
            if member is None:
                raise GenerationError(f"{class_name}.{property_name} is not a property in the API dump")
            value_type = member.get("ValueType")
            if not isinstance(value_type, dict):
                raise GenerationError(f"{class_name}.{property_name} has no ValueType")
            override_key = f"{class_name}.{property_name}"
            rendered_type = overrides.get(override_key)
            if rendered_type is None:
                rendered_type = api_type(value_type, mappings, override_key)
            declarations.append(f"    {property_name}: {rendered_type}")

        for function_name in requested_functions:
            member = members.get(("Function", function_name))
            if member is None:
                raise GenerationError(f"{class_name}.{function_name} is not a function in the API dump")
            parameters = member.get("Parameters", [])
            if not isinstance(parameters, list):
                raise GenerationError(f"{class_name}.{function_name} has malformed Parameters")
            rendered_parameters = ["self"]
            for parameter in parameters:
                if not isinstance(parameter, dict):
                    raise GenerationError(f"{class_name}.{function_name} has a malformed parameter")
                name = parameter.get("Name")
                parameter_type = parameter.get("Type")
                if not isinstance(name, str) or not isinstance(parameter_type, dict):
                    raise GenerationError(f"{class_name}.{function_name} has an incomplete parameter")
                override_key = f"{class_name}.{function_name}.{name}"
                rendered_type = overrides.get(override_key)
                if rendered_type is None:
                    rendered_type = api_type(parameter_type, mappings, override_key)
                    if "Default" in parameter and not rendered_type.endswith("?"):
                        rendered_type += "?"
                rendered_parameters.append(f"{name}: {rendered_type}")

            return_type = member.get("ReturnType")
            if not isinstance(return_type, dict):
                raise GenerationError(f"{class_name}.{function_name} has no ReturnType")
            return_override = overrides.get(f"{class_name}.{function_name}.return")
            rendered_return = return_override or api_type(
                return_type, mappings, f"{class_name}.{function_name}.return"
            )
            declarations.append(
                f"    function {function_name}({', '.join(rendered_parameters)}): {rendered_return}"
            )

        lines.extend(declarations)
        lines.append("end")
        lines.append("")

    globals_config = manifest.get("globals", {})
    if not isinstance(globals_config, dict):
        raise GenerationError("global declarations must be an object")
    for global_name, type_name in globals_config.items():
        if not isinstance(global_name, str) or not isinstance(type_name, str):
            raise GenerationError("global declarations must map names to class names")
        if type_name not in classes_config:
            raise GenerationError(f"global {global_name!r} references non-allowlisted type {type_name!r}")
        lines.append(f"declare {global_name}: {type_name}")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--api-dump", type=Path, help="Path to the version-pinned API dump in the external cache.")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="Generated Luau declaration output path.")
    parser.add_argument("--check", action="store_true", help="Compare generated output with the checked-in file.")
    args = parser.parse_args()

    try:
        manifest = load_json(MANIFEST, "Engine API surface manifest")
        reference = manifest.get("reference", {})
        dump_path = args.api_dump or cache_path(str(reference.get("uploadId", "")))
        if not dump_path.is_file():
            raise GenerationError(
                f"API dump not found at {dump_path}; fetch it with scripts/fetch_studio_api_dump.py"
            )
        dump_size = dump_path.stat().st_size
        if dump_size <= 0 or dump_size > MAX_DUMP_BYTES:
            raise GenerationError(f"API dump size {dump_size} is outside the allowed range")
        expected_size = reference.get("apiDumpBytes")
        if dump_size != expected_size:
            raise GenerationError(f"API dump size mismatch: expected {expected_size}, got {dump_size}")
        actual_sha256 = sha256_file(dump_path)
        expected_sha256 = reference.get("apiDumpSha256")
        if actual_sha256 != expected_sha256:
            raise GenerationError(
                f"API dump SHA-256 mismatch: expected {expected_sha256}, got {actual_sha256}"
            )
        api_dump = load_json(dump_path, "Roblox API dump")
        output_text = generate(manifest, api_dump)

        if args.check:
            try:
                checked_in = args.output.read_text(encoding="utf-8")
            except OSError as exc:
                raise GenerationError(f"Could not read generated output {args.output}: {exc}") from exc
            if checked_in != output_text:
                raise GenerationError(
                    f"{args.output} is stale; run scripts/generate_studio_engine_types.py to regenerate it"
                )
            print(f"checked {args.output} against API dump {actual_sha256}")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(output_text, encoding="utf-8", newline="\n")
            print(f"generated {args.output} from API dump {actual_sha256}")
        return 0
    except GenerationError as exc:
        print(f"engine type generation failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
